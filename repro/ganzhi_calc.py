# 干支日数差计算器 v1.0（验辞回测工程专用）
# 原理：六十甲子=CRT同步环。日n干=n mod 10，支=n mod 12。
STEMS="甲乙丙丁戊己庚辛壬癸"; BRANCHES="子丑寅卯辰巳午未申酉戌亥"
def idx(name):
    s,b=STEMS.index(name[0]),BRANCHES.index(name[1])
    assert s%2==b%2, f"{name}非合法干支"
    n=s
    while n%12!=b: n+=10
    return n%60
def gap(a,b):
    """b距a的天数差（mod 60取最小非负）"""
    return (idx(b)-idx(a))%60
# 校准结论（v1.0，2026-11-24）
# ①三例✓，CRT计算器成立。②商代"第N日"=干支差+1（含首日计）：'迄至五日丁酉'对应diff=4，实锤。
# ③合17055案例暴露配对陷阱：同骨多辞时验辞归属须逐辞核，禁止见骨就配。

tests=[("癸巳","丁酉",4,"《菁华》1/《合》6057：'迄至五日丁酉'→diff=4，商代第N日=差值+1（含首日计）"),
       ("癸丑","甲寅",1,"《合》137正：次日应验（无N字）"),
       ("癸巳","甲午",1,"《合》10405正：'若称，甲午'次日"),
       ("丙午","壬申",26,"《合》17055：'二旬又八日壬申'——★配对警报：diff=26≠28，且引文壬字带方括号=释文存疑。此验辞或系同骨另一辞之验（同片多辞陷阱实案），不作计算器反例，转登记为提取规则陷阱#7实证")]
for a,b,exp,src in tests:
    d=gap(a,b); ok="✓" if d==exp else "✗"
    print(f"{a}→{b}: diff={d} 预期={exp} {ok}  {src}")
